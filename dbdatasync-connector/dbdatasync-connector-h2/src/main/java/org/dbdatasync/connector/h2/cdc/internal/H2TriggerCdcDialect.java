package org.dbdatasync.connector.h2.cdc.internal;

import org.dbdatasync.sdk.cdc.trigger.TriggerCdcDialect;
import org.dbdatasync.sdk.model.Field;

import java.util.Collections;
import java.util.List;
import java.util.Locale;

/**
 * Wave26：H2 Trigger CDC 方言（内联 Java 源码触发器）。
 *
 * <p>H2 2.x 的 {@code CREATE TRIGGER ... CALL 'class'} 在数据库重开时按当时环境重新
 * 实例化触发器类，无法携带建表时上下文（已实测踩坑：所有触发器共享最后一次创建的
 * 上下文，op 全部错乱）。因此本方言改用 H2 的内联源码触发器语法：</p>
 * <pre>
 * CREATE TRIGGER IF NOT EXISTS "name" AFTER INSERT ON tbl FOR EACH ROW AS $$ ... $$
 * </pre>
 * 源码定义 {@code org.h2.dynamic.trigger.<触发器名>} 类，含一个返回
 * {@code org.h2.api.Trigger} 的 public static 工厂方法；日志表/业务表/操作/字段
 * 上下文直接烘焙进源码常量，与实例化时机无关（已实测验证重开库后仍正确）。</p>
 *
 * <p><b>运行时要求</b>：内联源码由 H2 SourceCompiler 经 javax.tools 编译，需要 JDK
 * （非 JRE）运行时；产品发行包按 JDK8 运行，满足条件。</p>
 *
 * @author DBDataSync
 * @version 2.1.6
 * @date 2026-11-09
 */
public class H2TriggerCdcDialect implements TriggerCdcDialect {

    @Override
    public String name() {
        return "h2";
    }

    @Override
    public String createLogTableSql(String logTable) {
        return "CREATE TABLE IF NOT EXISTS " + logTable + " ("
                + "seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "tbl VARCHAR(512) NOT NULL, op VARCHAR(16) NOT NULL, pk VARCHAR(512), payload CLOB, ts BIGINT)";
    }

    @Override
    public List<String> createTriggerSqls(String logTable, String tableName, String operation, List<Field> columns) {
        String op = operation.toUpperCase(Locale.ROOT);
        String triggerName = TriggerCdcDialect.triggerSuffix(tableName, op);
        // H2 带引号标识符区分大小写：业务表名不加引号，与建表时大小写习惯无关
        String sql = "CREATE TRIGGER IF NOT EXISTS \"" + triggerName + "\""
                + " AFTER " + op + " ON " + tableName
                + " FOR EACH ROW AS $$" + inlineSource(triggerName, logTable, tableName, op, columns) + "$$";
        return Collections.singletonList(sql);
    }

    @Override
    public boolean javaBodyTriggers() {
        return false;
    }

    /**
     * 内联触发器源码：org.h2.dynamic.trigger 包 + 与触发器名一致的类 +
     * 返回 {@code org.h2.api.Trigger} 的 public static 工厂方法（H2 loadFromSource 契约：
     * 调用第一个非 _/main 的 public static 无参方法并强转 Trigger）。
     */
    static String inlineSource(String triggerName, String logTable, String tableName,
                               String operation, List<Field> columns) {
        String row = "DELETE".equals(operation) ? "oldRow" : "newRow";
        StringBuilder payload = new StringBuilder();
        String[] names = new String[columns.size()];
        for (int i = 0; i < columns.size(); i++) {
            names[i] = columns.get(i).getName();
            if (i > 0) {
                payload.append(" + \";\" + ");
            }
            // NULL 必须不带引号写入，unquote 还原时才区分 null 与字符串 "NULL"
            payload.append('"').append(javaEscape(names[i])).append("=\" + (row[").append(i)
                    .append("] == null ? \"NULL\" : \"'\" + String.valueOf(row[").append(i)
                    .append("]).replace(\"'\", \"''\") + \"'\")");
        }
        return "package org.h2.dynamic.trigger;\n"
                + "import java.sql.Connection;\n"
                + "import java.sql.PreparedStatement;\n"
                + "import org.h2.api.Trigger;\n"
                + "public class " + triggerName + " {\n"
                + "  public static Trigger instance() {\n"
                + "    return new Trigger() {\n"
                + "      public void fire(Connection conn, Object[] oldRow, Object[] newRow) throws java.sql.SQLException {\n"
                + "        Object[] row = " + row + ";\n"
                + "        if (row == null) return;\n"
                + "        PreparedStatement ps = conn.prepareStatement(\"INSERT INTO " + logTable
                + "(tbl,op,pk,payload,ts) VALUES (?,?,?,?,?)\");\n"
                + "        ps.setString(1, \"" + javaEscape(tableName) + "\");\n"
                + "        ps.setString(2, \"" + operation + "\");\n"
                + "        ps.setObject(3, row[0]);\n"
                + "        ps.setString(4, " + payload.toString() + ");\n"
                + "        ps.setLong(5, System.currentTimeMillis());\n"
                + "        ps.executeUpdate();\n"
                + "        ps.close();\n"
                + "      }\n"
                + "    };\n"
                + "  }\n"
                + "}\n";
    }

    /** Java 字符串字面量转义（\ 与 "） */
    static String javaEscape(String raw) {
        return raw == null ? "" : raw.replace("\\", "\\\\").replace("\"", "\\\"");
    }
}
