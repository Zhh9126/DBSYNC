package org.dbdatasync.connector.oracle.cdc.trigger.internal;

import org.dbdatasync.sdk.cdc.trigger.TriggerCdcDialect;
import org.dbdatasync.sdk.model.Field;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Wave28：Oracle Trigger CDC 方言（SQL 体触发器，:NEW/:OLD 别名）。
 *
 * <p>定位：Oracle {@code OracleListener} 走 LogMiner 协议（需归档模式 + 补充日志 +
 * LogMining 权限）；Trigger CDC 是免归档的兜底捕获路径。语法与达梦方言同构
 * （达梦兼容 Oracle），差异在幂等建表：Oracle 12c 之前无 IDENTITY、
 * 无 {@code CREATE TABLE IF NOT EXISTS}，因此建表与自增列用 PL/SQL 异常吞块包装。</p>
 *
 * <p>实现要点：影子表 {@code seq NUMBER(19) GENERATED BY DEFAULT AS IDENTITY}
 * （需 Oracle 12c+）；触发器 {@code CREATE OR REPLACE} 天然幂等；时间戳用
 * {@code (SYSDATE - TO_DATE('1970-01-01','YYYY-MM-DD')) * 86400000} 近似毫秒（本地时区）。</p>
 *
 * <p><b>诚实边界</b>：SQL 生成有离线单测校验形状，本机无 Oracle 实例未真实执行；
 * 首次启用请在测试库验证 installSchema/installTriggers。</p>
 *
 * @author DBDataSync
 * @version 2.1.7
 * @date 2026-11-10
 */
public class OracleTriggerCdcDialect implements TriggerCdcDialect {

    @Override
    public String name() {
        return "oracle";
    }

    @Override
    public String createLogTableSql(String logTable) {
        // Oracle 无 CREATE TABLE IF NOT EXISTS：用 PL/SQL 块捕获 ORA-00955（表已存在）实现幂等
        return "BEGIN EXECUTE IMMEDIATE 'CREATE TABLE " + logTable + " ("
                + "seq NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "tbl VARCHAR2(512) NOT NULL, op VARCHAR2(16) NOT NULL, pk VARCHAR2(512), payload CLOB, ts NUMBER(19))' "
                + "EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;";
    }

    @Override
    public List<String> createTriggerSqls(String logTable, String tableName, String operation, List<Field> columns) {
        String op = operation.toUpperCase(Locale.ROOT);
        String suffix = operation.toLowerCase(Locale.ROOT);
        String rowAlias = "DELETE".equalsIgnoreCase(operation) ? ":OLD" : ":NEW";
        StringBuilder payload = new StringBuilder();
        for (int i = 0; i < columns.size(); i++) {
            if (i > 0) {
                payload.append(" || ';' || ");
            }
            payload.append(valueExpr(columns.get(i).getName(), rowAlias));
        }
        String sql = "CREATE OR REPLACE TRIGGER \"__dbsync_cdc_" + suffix + "_" + sanitize(tableName) + "\""
                + " AFTER " + op + " ON \"" + tableName + "\" FOR EACH ROW"
                + " BEGIN INSERT INTO " + logTable + "(tbl,op,pk,payload,ts) VALUES ("
                + "'" + tableName + "', '" + op + "', " + rowAlias + ".\"" + columns.get(0).getName() + "\", "
                + payload.toString() + ", "
                + "ROUND((SYSDATE - TO_DATE('1970-01-01','YYYY-MM-DD')) * 86400000)); END";
        List<String> sqls = new ArrayList<>();
        sqls.add(sql);
        return sqls;
    }

    /**
     * {@code 'col=' || COALESCE('''' || REPLACE(CAST(:NEW."col" AS VARCHAR(4000)),'''','''''')||'''','NULL')}
     *
     * <p>与达梦方言同构：NULL 不带引号写入，单引号双写防注入。</p>
     */
    public static String valueExpr(String column, String rowAlias) {
        return "'" + column + "=' || COALESCE('''' || REPLACE(CAST(" + rowAlias + ".\"" + column
                + "\" AS VARCHAR(4000)), '''', '''''') || '''', 'NULL')";
    }

    @Override
    public boolean javaBodyTriggers() {
        return false;
    }

    /** Oracle 无 LIMIT：12c+ 用 FETCH FIRST 分页 */
    @Override
    public String pollPageSql(String logTable, int batchSize) {
        return "SELECT seq,tbl,op,pk,payload,ts FROM " + logTable
                + " WHERE seq > ? ORDER BY seq FETCH FIRST " + batchSize + " ROWS ONLY";
    }

    static String sanitize(String name) {
        return name.replaceAll("[^A-Za-z0-9_]", "_");
    }
}
