package org.dbdatasync.connector.oracle.cdc.trigger;

import org.dbdatasync.connector.oracle.cdc.trigger.internal.OracleTriggerCdcDialect;
import org.dbdatasync.sdk.model.Field;
import org.junit.Test;

import java.sql.Types;
import java.util.Arrays;
import java.util.List;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

/**
 * Wave28：Oracle Trigger CDC 方言 SQL 生成形状测试（离线，不连真实 Oracle）。
 * 真实执行属诚实边界外项：首次启用需在真实 Oracle 测试库验证（需 12c+）。
 */
public class Wave28OracleTriggerDialectTest {

    private final OracleTriggerCdcDialect dialect = new OracleTriggerCdcDialect();

    private List<Field> columns() {
        return Arrays.asList(
                new Field("id", "NUMBER", Types.NUMERIC),
                new Field("name", "VARCHAR2", Types.VARCHAR));
    }

    @Test
    public void logTableSqlIsIdempotentViaPlsqlBlock() {
        String sql = dialect.createLogTableSql("__DBSYNC_CDC_LOG");
        assertTrue("Oracle 无 IF NOT EXISTS，必须用 PL/SQL 吞 ORA-00955 幂等建表",
                sql.startsWith("BEGIN EXECUTE IMMEDIATE 'CREATE TABLE"));
        assertTrue(sql.contains("seq NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"));
        assertTrue(sql.contains("EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;"));
    }

    @Test
    public void insertTriggerUsesNewAliasAndReplace() {
        String sql = dialect.createTriggerSqls("__DBSYNC_CDC_LOG", "T1", "INSERT", columns()).get(0);
        assertTrue(sql.contains("CREATE OR REPLACE TRIGGER \"__dbsync_cdc_insert_T1\""));
        assertTrue(sql.contains("AFTER INSERT ON \"T1\" FOR EACH ROW"));
        assertTrue(sql.contains(":NEW.\"id\""));
        assertTrue("payload 需双写单引号防注入", sql.contains("REPLACE(CAST(:NEW.\"name\" AS VARCHAR(4000)), '''', '''''')"));
        assertTrue("NULL 需 COALESCE 兜底", sql.contains("COALESCE"));
        assertTrue(sql.contains("ROUND((SYSDATE - TO_DATE('1970-01-01','YYYY-MM-DD')) * 86400000)"));
        assertTrue(sql.endsWith("; END"));
    }

    @Test
    public void deleteTriggerUsesOldAlias() {
        String sql = dialect.createTriggerSqls("__DBSYNC_CDC_LOG", "T1", "DELETE", columns()).get(0);
        assertTrue(sql.contains("AFTER DELETE ON \"T1\""));
        assertTrue(sql.contains(":OLD.\"id\""));
        assertFalse(sql.contains(":NEW"));
    }

    @Test
    public void valueExprShapeMatchesDameng() {
        String expr = OracleTriggerCdcDialect.valueExpr("amount", ":NEW");
        assertEquals("'amount=' || COALESCE('''' || REPLACE(CAST(:NEW.\"amount\" AS VARCHAR(4000)), '''', '''''') || '''', 'NULL')", expr);
    }

    @Test
    public void pollPageSqlUsesFetchFirst() {
        assertTrue(dialect.pollPageSql("__DBSYNC_CDC_LOG", 500).contains("FETCH FIRST 500 ROWS ONLY"));
    }
}
